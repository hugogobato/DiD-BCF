# The true estimand is replication-specific (it is an average of the realised
# CATT over that replication's treated units), so ``emp_sd`` -- the dispersion of
# the point estimate -- also contains the variation of the target itself.  The
# Monte-Carlo SD of the *error* is the quantity the bias/variance decomposition
# wants, and it is recovered from the reported RMSE and bias.
met["sd_err"] = np.sqrt(np.clip(met["rmse"] ** 2 - met["bias"] ** 2, 0, None))


# --------------------------------------------------------------------------- #
# Table 0 -- what was actually run
# --------------------------------------------------------------------------- #
def tab_grid():
    g = grid.groupby(["setting", "N", "method"])["n_reps"].max().reset_index()
    piv = g.pivot_table(index=["setting", "N"], columns="method",
                        values="n_reps", aggfunc="max")
    piv = piv.reindex(columns=[m for m in METHOD_ORDER if m in piv.columns])
    piv = piv.reindex([(s, n) for s in SCEN_ORDER
                       for n in sorted(grid[grid.setting == s].N.unique())])
    body = []
    for (s, n), row in piv.iterrows():
        cells = [("--" if pd.isna(v) else f"{int(v)}") for v in row]
        body.append(f"{SCEN_TEX[s]} & {int(n)} & " + " & ".join(cells) + r" \\")
    head = ["Scenario & $N$ & " +
            " & ".join(rf"\rotatebox{{60}}{{{TEXLABEL[c]}}}" for c in piv.columns)
            + r" \\"]
    write_tex_table(
        os.path.join(TAB, "tab_grid.tex"), head, body,
        "ll" + "r" * len(piv.columns),
        "Monte-Carlo replications available per scenario, panel size and estimator "
        "(maximum over the three linearity degrees). A dash marks a cell that was "
        "not run.",
        "tab:grid",
        notes=r"\emph{Note.} Every scenario is additionally run at each linearity "
              r"degree $d\in\{1,2,3\}$. The DoubleML DR-DiD sweep cells are "
              r"complete at all four panel sizes; "
              r"TWFE is not reported for the staggered scenarios at the "
              r"cohort-by-time level because pooling cohorts is precisely the "
              r"contamination it suffers from.")


