def fig_es_bias():
    """Bias against event time for *every* method, including the cohort-by-time
    estimators that Figure \\ref{fig:es-methods} cannot show.

    Levels cannot mix the two estimator families: the event-time target of the
    ES-reporting methods is weighted by realised cohort sizes, whereas a
    cohort-by-time estimator can only be collapsed to event time by averaging
    its cells, and the two targets differ by up to 0.24 in the contamination
    design.  Bias is immune to that: the mean of the per-cell biases at event
    time k is exactly the bias of the cell-averaged estimate, so each method is
    scored against its own target and all of them share the zero line.
    """
    fig, axes = plt.subplots(2, 2, figsize=(9.0, 6.0), sharex=True)
    for col, s in enumerate(["D_staggered", "D_contamination"]):
        es = met[(met.setting == s) & (met.estimand_type == "ES") &
                 (met.linearity_degree == 1)].copy()
        es["kk"] = es.estimand_id.str.replace("k=", "").astype(int)
        ga = _gt(met[(met.setting == s) & (met.estimand_type == "GATT") &
                     (met.linearity_degree == 1)])
        ga = ga.groupby(["method", "kk"], as_index=False).bias.mean()
        # Top row keeps TWFE and so is dominated by it; the bottom row drops it
        # and rescales, which is the only way the remaining methods separate.
        for row, drop_twfe in enumerate([False, True]):
            ax = axes[row, col]
            ax.axhline(0, color="#1a1a1a", alpha=0.18, linewidth=7,
                       solid_capstyle="round", zorder=0)
            ax.axhline(0, color="#1a1a1a", linewidth=1.0, zorder=1)
            for m in METHOD_ORDER:
                if drop_twfe and m == "twfe":
                    continue
                src = es if m in set(es.method) else ga
                blk = src[src.method == m].sort_values("kk")
                if blk.empty:
                    continue
                lab = PLAINLABEL[m] + ("" if m in set(es.method) else " (cells)")
                ax.plot(blk.kk, blk.bias, DASH[m], color=COLOR[m],
                        marker=MARKER[m], markersize=5.5, linewidth=1.5,
                        label=lab, markeredgecolor="white", markeredgewidth=0.5)
            ax.set_ylabel("bias")
            ax.set_xticks(sorted(es.kk.unique()))
            if row == 0:
                ax.set_title(s.replace("_", " "), fontsize=9, loc="left")
            else:
                ax.set_title("excluding TWFE", fontsize=8, loc="left",
                             color="#52514e")
                ax.set_xlabel("event time $k$")
    handles, labels = axes[1, 0].get_legend_handles_labels()
    hb, lb = axes[0, 0].get_legend_handles_labels()
    i = lb.index(PLAINLABEL["twfe"])
    handles, labels = handles + [hb[i]], labels + [lb[i]]
    fig.legend(handles, labels, loc="lower center", ncol=4, fontsize=8,
               bbox_to_anchor=(0.5, -0.11))
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "fig_es_bias.pdf"), bbox_inches="tight")
    plt.close(fig)
    print("  -> figures/fig_es_bias.pdf")


