def _f(x, n=3):
    if pd.isna(x):
        return "--"
    return f"{x:.{n}f}"


def _gt(df):
    """Split a ``g=<g>_t=<t>`` estimand id into cohort, calendar time, event time."""
    out = df.copy()
    parts = out.estimand_id.str.extract(r"g=(\d+)_t=(\d+)").astype(float)
    out["gg"], out["tt"] = parts[0], parts[1]
    out["kk"] = out["tt"] - out["gg"]
    return out


def write_tex_table(path, header_rows, body_rows, colspec, caption, label,
                    notes=None, small=True, longtable=None):
    """Emit a booktabs table; tall ones become longtables so they page-break."""
    if longtable is None:
        longtable = len(body_rows) > 34
    if longtable:
        return _write_longtable(path, header_rows, body_rows, colspec, caption,
                                label, notes)
    lines = [r"% Auto-generated by Results/analysis/make_analysis.py -- do not edit by hand.",
             r"\begin{table}[htbp]", r"\centering"]
    if small:
        lines.append(r"\footnotesize")
    lines.append(rf"\caption{{{caption}}}")
    lines.append(rf"\label{{{label}}}")
    lines.append(rf"\begin{{tabular}}{{{colspec}}}")
    lines.append(r"\toprule")
    lines += header_rows
    lines.append(r"\midrule")
    lines += body_rows
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    if notes:
        lines.append(r"\begin{minipage}{\linewidth}\vspace{2pt}\footnotesize")
        lines.append(notes)
        lines.append(r"\end{minipage}")
    lines.append(r"\end{table}")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("  ->", os.path.relpath(path, RES))


def _write_longtable(path, header_rows, body_rows, colspec, caption, label,
                     notes):
    head = "\n".join(header_rows)
    lines = [r"% Auto-generated by Results/analysis/make_analysis.py -- do not edit by hand.",
             r"{\footnotesize",
             rf"\begin{{longtable}}{{{colspec}}}",
             rf"\caption{{{caption}}}\label{{{label}}}\\",
             r"\toprule", head, r"\midrule", r"\endfirsthead",
             r"\multicolumn{" + str(len(colspec.replace("|", ""))) +
             r"}{l}{\emph{\footnotesize Table \ref{" + label +
             r"} continued from the previous page.}}\\",
             r"\toprule", head, r"\midrule", r"\endhead",
             r"\midrule",
             r"\multicolumn{" + str(len(colspec.replace("|", ""))) +
             r"}{r}{\emph{\footnotesize continued on the next page}}\\",
             r"\endfoot", r"\bottomrule", r"\endlastfoot"]
    lines += body_rows
    lines.append(r"\end{longtable}")
    if notes:
        lines.append(r"\noindent " + notes + r"\par\vspace{6pt}")
    lines.append(r"}")
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("  ->", os.path.relpath(path, RES), "(longtable)")


