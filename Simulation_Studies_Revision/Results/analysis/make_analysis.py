def fig_calibration():
    """Coverage vs calibration ratio -- one dot per (scenario, method, d)."""
    sub = met[(met.estimand_type == "GATT") & (met.estimand_id == "g=4_t=4") &
              (met.N == 200) & (met.setting.isin(SCEN_ORDER))]
    fig, ax = plt.subplots(figsize=(6.0, 4.0))
    for m in METHOD_ORDER:
        blk = sub[sub.method == m]
        if blk.empty:
            continue
        # Open marks: the well-calibrated estimators pile up near (1, 0.95) and
        # filled marks would hide one another there.
        ax.scatter(blk.sd_ratio.clip(upper=3.2), blk.cover95, s=42,
                   facecolors="none", edgecolors=COLOR[m], marker=MARKER[m],
                   label=PLAINLABEL[m], linewidth=1.3, alpha=0.95, zorder=3)
    ax.axhline(0.95, color="#8a8a85", linewidth=1.0, linestyle=(0, (1, 2)))
    ax.axvline(1.0, color="#8a8a85", linewidth=1.0, linestyle=(0, (1, 2)))
    ax.annotate("nominal coverage", (0.02, 0.955), fontsize=7.5, color="#52514e")
    ax.annotate("calibrated\ndispersion", (1.05, 0.06), fontsize=7.5, color="#52514e")
    ax.set_xlabel(r"calibration ratio $\overline{\mathrm{sd}}/\mathrm{SD}$"
                  "  (values >3.2 clipped)")
    ax.set_ylabel("95% interval coverage")
    ax.set_ylim(-0.03, 1.05)
    ax.legend(fontsize=7.5, ncol=2, loc="lower right")
    fig.tight_layout()
    fig.savefig(os.path.join(FIG, "fig_calibration.pdf"), bbox_inches="tight")
    plt.close(fig)
    print("  -> figures/fig_calibration.pdf")


