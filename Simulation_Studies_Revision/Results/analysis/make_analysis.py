def tab_b1(estimand_type, estimand_id, fname, label, caption):
    sub = met[(met.estimand_type == estimand_type) &
              (met.estimand_id == estimand_id) & (met.N == 200) &
              (met.setting.isin(["B1_baseline", "B1_strong_confounder",
                                 "B1_serial_corr", "B1_selection_obs"]))]
    body = []
    for s in ["B1_baseline", "B1_strong_confounder", "B1_serial_corr",
              "B1_selection_obs"]:
        body.append(rf"\multicolumn{{9}}{{l}}{{\textit{{{SCEN_TEX[s]}}}}} \\")
        for d in (1, 2, 3):
            block = _order(sub[(sub.setting == s) & (sub.linearity_degree == d)])
            for _, r in block.iterrows():
                body.append(
                    f"\\quad {TEXLABEL[r.method]} & {d} & {_f(r.bias)} & "
                    f"{_f(r.sd_err)} & {_f(r.rmse)} & {_f(r.cover90)} & "
                    f"{_f(r.cover95)} & {_f(r.len95)} & {_f(r.sd_ratio)} \\\\")
        body.append(r"\addlinespace")
    head = [r"Estimator & $d$ & Bias & SD(err) & RMSE & Cov.90 & Cov.95 & Len.95 & "
            r"$\overline{\mathrm{sd}}/\mathrm{SD}$ \\"]
    write_tex_table(os.path.join(TAB, fname), head, body,
                    "lr" + "r" * 7, caption, label,
                    notes=r"\emph{Note.} $N=200$, 100 replications, $d$ is the "
                          r"linearity degree. Bias and RMSE are Monte-Carlo "
                          r"moments of the estimation error and SD(err) is its "
                          r"standard deviation, $\sqrt{\text{RMSE}^2-\text{Bias}^2}$ "
                          r"(the target itself varies by replication, so the raw "
                          r"dispersion of the estimate is not the error SD); Cov.90/95 are "
                          r"credible/confidence-interval coverage rates; Len.95 "
                          r"the average 95\% interval length; "
                          r"$\overline{\mathrm{sd}}/\mathrm{SD}$ the calibration "
                          r"ratio of the average reported posterior/standard "
                          r"error to the Monte-Carlo SD (1 is perfect "
                          r"calibration, $<1$ over-confident).")


def tab_null():
    sub = met[(met.setting == "B1_null") & (met.N == 200)]
    body = []
    for et, eid in (("ATT", "ATT"), ("ES", "k=0"), ("GATT", "g=4_t=4")):
        blk = sub[(sub.estimand_type == et) & (sub.estimand_id == eid)]
        if blk.empty:
            continue
        eid_tex = eid.replace("_", r"\_").replace("=", "$=$")
        body.append(rf"\multicolumn{{8}}{{l}}{{\textit{{{et}, {eid_tex}}}}} \\")
        for d in (1, 2, 3):
            for _, r in _order(blk[blk.linearity_degree == d]).iterrows():
                body.append(
                    f"\\quad {TEXLABEL[r.method]} & {d} & {_f(r.bias)} & "
                    f"{_f(r.sd_err)} & {_f(r.cover90)} & {_f(r.cover95)} & "
                    f"{_f(r.reject05)} & {_f(r.mcse_reject05)} \\\\")
        body.append(r"\addlinespace")
    head = [r"Estimator & $d$ & Bias & SD(err) & Cov.90 & Cov.95 & Size (5\%) & MCSE \\"]
    write_tex_table(
        os.path.join(TAB, "tab_null.tex"), head, body, "lr" + "r" * 6,
        "Behaviour under the sharp null $\\tau\\equiv 0$ (scenario "
        "\\texttt{B1\\_null}): bias, dispersion, coverage and the empirical size "
        "of the two-sided 5\\% test.", "tab:null",
        notes=r"\emph{Note.} $N=200$; 100 replications for the model-based "
              r"estimators and 200 for TWFE. A nominal 5\% test should reject in "
              r"$0.05$ of replications; MCSE is the Monte-Carlo standard error of "
              r"that rejection rate.")


