#!/usr/bin/env python3
"""Tables for the small-panel end of the B2 sample-size sweep (N = 50, 100).

``make_analysis.py`` draws the whole sweep on one axis, which is the right view
for the asymptotics but compresses the two smallest panels into the left margin.
The small-sample question is different in kind: at N = 50 the comparison is no
longer "who converges faster" but "who still returns an estimate, and is the
reported uncertainty honest".  This script therefore reports the small end on
its own, with the estimability column (``retention``) kept next to the
point-estimation columns rather than in a footnote.

Inputs
------
``Results/aggregated/metrics_all.csv``   scalar metrics per design cell
``Results/aggregated/surface_all.csv``   within-replication CATT-surface metrics

Outputs
-------
``Results/tables/tab_smalln.tex``          GATT(4,4) and ATT at N in {50,100,200}
``Results/tables/tab_smalln_surface.tex``  CATT surface over the same panels
``Results/figures/fig_smalln.pdf``         RMSE and coverage against N
"""
from __future__ import annotations

import os
import sys

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
RES = os.path.dirname(HERE)
ROOT = os.path.dirname(RES)
AGG = os.path.join(RES, "aggregated")
TAB = os.path.join(RES, "tables")
FIG = os.path.join(RES, "figures")

import matplotlib.pyplot as plt                                       # noqa: E402
from style import COLOR, MARKER, DASH, PLAINLABEL, TEXLABEL, METHOD_ORDER  # noqa: E402
sys.path.insert(0, ROOT)
from did_bcf_revision.config import N_SWEEP  # noqa: E402

# N = 200 is carried as the reference column: it is the base panel of every
# other scenario in the suite, so "how much worse is N = 50" is the question the
# table has to answer, not "what does N = 50 look like in isolation".
NS = [50, 100, 200]
SWEEPS = ["B2_sweep", "B2_sweep_serial"]
SCEN_LABEL = {"B2_sweep": "B2 ordinary", "B2_sweep_serial": "B2 serial"}


def _f(x, n=3):
    return "--" if pd.isna(x) else f"{x:.{n}f}"


def _rows(met, setting, etype, eid, degree):
    sub = met[(met.setting == setting) & (met.estimand_type == etype) &
              (met.estimand_id == eid) & (met.linearity_degree == degree) &
              met.N.isin(NS)]
    out = []
    for m in METHOD_ORDER:
        blk = sub[sub.method == m]
        if blk.empty:
            continue
        cells = []
        for N in NS:
            r = blk[blk.N == N]
            if r.empty:
                cells += ["--"] * 4
                continue
            r = r.iloc[0]
            # A retention below one means the row is computed on a subsample;
            # marking it here keeps the comparison honest inside the table.
            star = r"$^{\dagger}$" if float(r.retention) < 0.999 else ""
            cells += [_f(r.bias), _f(r.rmse), _f(r.cover95, 2) + star,
                      _f(r.sd_ratio, 2)]
        out.append((TEXLABEL[m], cells))
    return out


def make_scalar_table(met, path, degree=1):
    lines = [r"% Auto-generated by Results/analysis/make_smalln_analysis.py.",
             r"\begin{table}[htbp]", r"\centering", r"\scriptsize",
             r"\setlength{\tabcolsep}{2.6pt}",
             r"\caption{The small-panel end of the B2 sweeps at linearity degree "
             r"$d=" + str(degree) + r"$. Bias, RMSE, 95\% coverage and the "
             r"calibration ratio $\overline{\mathrm{sd}}/\mathrm{SD}$ for the "
             r"cohort-time target $\mathrm{GATT}(4,4)$ and the pooled "
             r"$\mathrm{ATT}$.}",
             r"\label{tab:smalln}",
             r"\begin{tabular}{ll" + "rrrr" * len(NS) + "}", r"\toprule",
             " & ".join([" ", " "] + [r"\multicolumn{4}{c}{$N=%d$}" % n
                                      for n in NS]) + r" \\",
             " ".join(r"\cmidrule(lr){%d-%d}" % (3 + 4 * i, 6 + 4 * i)
                      for i in range(len(NS))),
             " & ".join(["Target", "Estimator"] +
                        ["Bias", "RMSE", "Cov.", r"$\overline{\mathrm{sd}}/\mathrm{SD}$"]
                        * len(NS)) + r" \\", r"\midrule"]
    for setting in SWEEPS:
        lines.append(r"\multicolumn{%d}{l}{\textit{%s}} \\"
                     % (2 + 4 * len(NS), SCEN_LABEL[setting]))
        for target, etype, eid in ((r"$\gatt(4,4)$", "GATT", "g=4_t=4"),
                                   (r"$\att$", "ATT", "ATT")):
            rows = _rows(met, setting, etype, eid, degree)
            for i, (lab, cells) in enumerate(rows):
                first = target if i == 0 else " "
                lines.append(" & ".join([first, lab] + cells) + r" \\")
            lines.append(r"\addlinespace[2pt]")
        lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\par\smallskip\footnotesize \emph{Note.} 100 replications per "
              r"cell. $^{\dagger}$computed on the replications in which the "
              r"estimator returned an estimate. TWFE was not run on the "
              r"sweeps below $N=200$. Gardner reports event-study coefficients "
              r"only and synthetic DiD a pooled ATT only, so neither appears "
              r"against every target.",
              r"\end{table}"]
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("  ->", os.path.relpath(path, ROOT))


def make_surface_table(surf, path, degree=1):
    sub = surf[(surf.linearity_degree == degree) & surf.N.isin(NS) &
               surf.setting.isin(SWEEPS)]
    lines = [r"% Auto-generated by Results/analysis/make_smalln_analysis.py.",
             r"\begin{table}[htbp]", r"\centering", r"\scriptsize",
             r"\setlength{\tabcolsep}{4pt}",
             r"\caption{Individual-level CATT surface at the small end of the "
             r"B2 sweeps, $d=" + str(degree) + r"$. Within-replication RMSE and "
             r"MAPE over the treated observations, and pointwise 95\% coverage, "
             r"averaged across replications.}",
             r"\label{tab:smallnsurface}",
             r"\begin{tabular}{ll" + "rrr" * len(NS) + "}", r"\toprule",
             " & ".join([" ", " "] + [r"\multicolumn{3}{c}{$N=%d$}" % n
                                      for n in NS]) + r" \\",
             " ".join(r"\cmidrule(lr){%d-%d}" % (3 + 3 * i, 5 + 3 * i)
                      for i in range(len(NS))),
             " & ".join(["Design", "Estimator"] +
                        ["RMSE", "MAPE", "Cov."] * len(NS)) + r" \\",
             r"\midrule"]
    for setting in SWEEPS:
        blk = sub[sub.setting == setting]
        first = True
        for m in METHOD_ORDER:
            g = blk[blk.method == m]
            if g.empty:
                continue
            cells = []
            for N in NS:
                r = g[g.N == N]
                if r.empty:
                    cells += ["--"] * 3
                    continue
                r = r.iloc[0]
                cells += [_f(r.surf_rmse_mean), _f(r.surf_mape_mean),
                          _f(r.surf_cover95_mean, 2)]
            lines.append(" & ".join([SCEN_LABEL[setting] if first else " ",
                                     TEXLABEL[m]] + cells) + r" \\")
            first = False
        lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\par\smallskip\footnotesize \emph{Note.} Every estimator other "
              r"than DiD-BCF reports a single number per cohort-time cell, so "
              r"its surface is that number broadcast to the individuals in the "
              r"cell; the comparison measures what is lost by not modelling "
              r"individual heterogeneity.", r"\end{table}"]
    with open(path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print("  ->", os.path.relpath(path, ROOT))


def make_figure(met, surf, path, degree=1):
    fig, axes = plt.subplots(1, 3, figsize=(11.0, 3.3))
    # Stale N=1600 result files are still on disk for some estimators; the live
    # sweep stops at 800, so plotting them would stretch the axis past its ticks.
    sub = met[(met.setting == "B2_sweep") & (met.estimand_type == "ATT") &
              (met.estimand_id == "ATT") & (met.linearity_degree == degree) &
              met.N.isin(N_SWEEP)]
    ssub = surf[(surf.setting == "B2_sweep") & (surf.linearity_degree == degree) &
                surf.N.isin(N_SWEEP)]
    panels = [(sub, "rmse", r"pooled ATT RMSE", True),
              (sub, "cover95", "pooled ATT 95% coverage", False),
              (ssub, "surf_rmse_mean", "CATT-surface RMSE", True)]
    for ax, (frame, col, ylab, logy) in zip(axes, panels):
        for m in METHOD_ORDER:
            blk = frame[frame.method == m].sort_values("N")
            if blk.empty or col not in blk:
                continue
            ax.plot(blk.N, blk[col], DASH[m], color=COLOR[m], marker=MARKER[m],
                    markersize=5.5, linewidth=1.6, label=PLAINLABEL[m],
                    markeredgecolor="white", markeredgewidth=0.5)
        ax.set_xscale("log", base=2)
        ax.set_xticks(list(N_SWEEP))
        ax.set_xticklabels([str(n) for n in N_SWEEP])
        ax.set_xlabel("panel size $N$")
        ax.set_ylabel(ylab)
        if logy:
            ax.set_yscale("log")
        if col == "cover95":
            ax.axhline(0.95, color="#8a8a85", linewidth=1.0, linestyle=(0, (1, 2)))
            ax.set_ylim(0.5, 1.05)
    handles, labels = axes[0].get_legend_handles_labels()
    h2, l2 = axes[2].get_legend_handles_labels()
    for h, l in zip(h2, l2):
        if l not in labels:
            handles.append(h); labels.append(l)
    fig.legend(handles, labels, loc="lower center", ncol=5, fontsize=8,
               bbox_to_anchor=(0.5, -0.12))
    fig.tight_layout()
    fig.savefig(path, bbox_inches="tight")
    plt.close(fig)
    print("  ->", os.path.relpath(path, ROOT))


def main():
    os.makedirs(TAB, exist_ok=True); os.makedirs(FIG, exist_ok=True)
    met = pd.read_csv(os.path.join(AGG, "metrics_all.csv"))
    surf = pd.read_csv(os.path.join(AGG, "surface_all.csv"))
    make_scalar_table(met, os.path.join(TAB, "tab_smalln.tex"))
    make_surface_table(surf, os.path.join(TAB, "tab_smalln_surface.tex"))
    make_figure(met, surf, os.path.join(FIG, "fig_smalln.pdf"))


if __name__ == "__main__":
    main()
